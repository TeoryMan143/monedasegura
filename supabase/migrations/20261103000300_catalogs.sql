create table public.currencies (
  code char(3) not null,
  name text not null,
  symbol text not null,
  decimals smallint not null,
  locale text not null,
  constraint currencies_pkey primary key (code),
  constraint currencies_decimals_check check (decimals >= 0 and decimals <= 4)
);

create table public.countries (
  code char(2) not null,
  name text not null,
  currency_code char(3) not null,
  primary_document_type public.document_type not null,
  phone_prefix text not null,
  constraint countries_pkey primary key (code),
  constraint countries_currency_code_fkey foreign key (currency_code) references public.currencies (code)
);

create table public.cities (
  id integer generated by default as identity not null,
  country_code char(2) not null,
  name text not null,
  region text,
  latitude numeric(9, 6) not null,
  longitude numeric(9, 6) not null,
  constraint cities_pkey primary key (id),
  constraint cities_country_code_name_key unique (country_code, name),
  constraint cities_latitude_check check (latitude >= -90 and latitude <= 90),
  constraint cities_longitude_check check (longitude >= -180 and longitude <= 180),
  constraint cities_country_code_fkey foreign key (country_code) references public.countries (code)
);

create table public.banks (
  id integer generated by default as identity not null,
  name text not null,
  country_code char(2) not null,
  swift_code text,
  is_own boolean not null default false,
  constraint banks_pkey primary key (id),
  constraint banks_swift_code_key unique (swift_code),
  constraint banks_country_code_fkey foreign key (country_code) references public.countries (code)
);

create table public.channels (
  code text not null,
  name text not null,
  country_code char(2),
  is_digital boolean not null,
  constraint channels_pkey primary key (code),
  constraint channels_country_code_fkey foreign key (country_code) references public.countries (code)
);

create table public.merchant_categories (
  mcc char(4) not null,
  description text not null,
  is_high_risk boolean not null default false,
  constraint merchant_categories_pkey primary key (mcc)
);

create table public.fraud_types (
  id smallint generated by default as identity not null,
  code varchar(5) not null,
  name text not null,
  description text not null,
  color char(7) not null,
  constraint fraud_types_pkey primary key (id),
  constraint fraud_types_code_key unique (code),
  constraint fraud_types_color_check check (color ~ '^#[0-9A-Fa-f]{6}$')
);

create table public.confidence_levels (
  level smallint not null,
  name text not null,
  meaning text not null,
  criteria text not null,
  sample_weight numeric(3, 2) not null,
  requires_justification boolean not null default false,
  constraint confidence_levels_pkey primary key (level),
  constraint confidence_levels_level_check check (level >= 1 and level <= 4)
);

create table public.severity_levels (
  level public.severity not null,
  sort_order smallint not null,
  name text not null,
  criteria text not null,
  constraint severity_levels_pkey primary key (level),
  constraint severity_levels_sort_order_key unique (sort_order)
);

create table public.severity_thresholds (
  currency_code char(3) not null,
  level public.severity not null,
  min_amount numeric(18, 2) not null,
  constraint severity_thresholds_pkey primary key (currency_code, level),
  constraint severity_thresholds_min_amount_check check (min_amount >= 0),
  constraint severity_thresholds_currency_code_fkey foreign key (currency_code) references public.currencies (code),
  constraint severity_thresholds_level_fkey foreign key (level) references public.severity_levels (level)
);
